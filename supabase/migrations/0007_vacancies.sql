-- =============================================================================
-- 0007_vacancies.sql
-- Таблица открытых вакансий в команду.
--
-- Раньше жило в `src/data/vacancies.ts`. Перенесли в Supabase, чтобы
-- открывать-закрывать вакансии и редактировать требования без пересборки.
--
-- Структура:
--   slug           — стабильный id ('vocalist', 'sound', 'tuner', 'artist',
--                    'video', 'smm', 'arranger', 'translator').
--   sort_order     — порядок отображения на странице «Набор».
--   requirements[] — список требований (массив строк).
--   conditions     — длинный текст про условия отклика (порядок слов важен).
--   is_open        — открыта ли вакансия. Закрытые не показываются на сайте,
--                    но остаются в БД и видны в админке.
-- =============================================================================

create table if not exists public.vacancies (
  slug text primary key,
  role text not null,
  requirements text[] not null default '{}',
  conditions text not null,
  is_open boolean not null default true,
  sort_order smallint not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists vacancies_open_sort_idx
  on public.vacancies (sort_order)
  where is_open = true;

alter table public.vacancies enable row level security;

-- Публичный SELECT только открытых вакансий.
drop policy if exists vacancies_select_public on public.vacancies;
create policy vacancies_select_public on public.vacancies
  for select to anon, authenticated
  using (is_open = true);

drop policy if exists vacancies_admin_all on public.vacancies;
create policy vacancies_admin_all on public.vacancies
  for all to authenticated
  using (private.is_admin())
  with check (private.is_admin());

revoke all on public.vacancies from anon, authenticated;
grant select on public.vacancies to anon, authenticated;
grant insert, update, delete on public.vacancies to authenticated;

